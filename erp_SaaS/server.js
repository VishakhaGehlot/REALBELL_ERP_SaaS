const express = require('express')
const app = express()
const path = require('path')
require('dotenv').config()
require('./dbconnection/DBconnection')
const session = require('express-session')
const { attachRolePermissions } = require('./middleware/permissionAuth')

app.use(session({
    secret: "Ravi",
    resave: false,
    saveUninitialized: false
}))

// IMPORTANT: Add BOTH of these middleware
app.use(express.json()); // This parses JSON data (what your frontend sends)
app.use(express.urlencoded({ extended: true })); // This parses form data
app.use(attachRolePermissions)
app.use(express.static(path.join(__dirname, 'public')))

const authRouter = require('./routers/auth')
const HomeRouter = require('./routers/Home')
const AccountRouter = require('./routers/Account')
const FaqRouter = require('./routers/faq')
const ManageRouter = require('./routers/Manage')
const queryRouter = require('./routers/query')
const leadsRouter = require('./routers/leads')
const solutionRouter = require('./routers/solution')
const financeRouter = require('./routers/finance')
const userRouter = require('./routers/user')
const premiumsRouter = require('./routers/premiums')
const FeatureRouter = require('./routers/feature')
const swiperRouter = require('./routers/swiper')
const footerRouter = require('./routers/footer')
const CRMRouter = require('./routers/CRM')
const hrmRouters = require('./routers/Hrm')
const smtpRouters = require('./routers/SmtpRouter')
const profileRouter=require('./routers/profile')
const zoomRouter=require("./routers/Zoom")
const productRouter=require('./routers/Product')
const permissionsRouter = require('./routers/permissions')
const subsRouter = require('./routers/pricing')
const erpModulesRouter = require('./routers/erpModules')

app.use('/', HomeRouter)
app.use('/', authRouter)
